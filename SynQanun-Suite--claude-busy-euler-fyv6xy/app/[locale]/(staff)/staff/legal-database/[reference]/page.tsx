/**
 * Law full-text reader — BUILD_PLAN.md §3, Batch 7.
 *
 * ===========================================================================
 * THE ONE BATCH 7 SCREEN WHOSE FIXTURE WAS BUILT FOR IT IN ADVANCE
 * ===========================================================================
 * fixtures/legal-database.ts was written in Batch 5 with a thirty-line header
 * arguing that the bodies must be Lorem Ipsum and ending "DO NOT 'IMPROVE'
 * THIS." That argument was made for exactly this screen: a result card shows an
 * excerpt and a reader shows the whole thing, so the reader is where readable
 * legal-sounding prose would have done its damage.
 *
 * So this renders Lorem Ipsum, full width, in numbered sections, and says in
 * two places that it is placeholder rather than law. A reader over placeholder
 * text is a strange-looking screen. It is the correct one, and the alternative
 * is the export.
 *
 * ===========================================================================
 * WHAT THE EXPORT PUT ON THIS SCREEN
 * ===========================================================================
 * This is the most dangerous export the project has received, and it is not a
 * close contest. Every previous worst case — the Legal Database's invented
 * judgments, the client signing screen's invented board resolution — is a
 * subset of what is on this one page.
 *
 *   · A REAL STATUTE WITH INVENTED TEXT, AT FULL LENGTH. "Federal Decree-Law
 *     No. 32 of 2021 on Commercial Companies", Article 71, in four numbered
 *     clauses, none of which is the actual Article 71. It carries a thirty-day
 *     pre-emption period, a ninety-day completion window and a court-appointed
 *     valuation procedure — specific, operative, checkable numbers that a
 *     lawyer would act on. The Arabic version gives the same article FIVE
 *     clauses and a five-working-day manager notification the English one does
 *     not have, so the two locales state different law under one citation.
 *
 *   · AN AUTHENTICATION CLAIM. "Original Arabic Text Authenticated: وزارة
 *     العدل" and "English Translation: Ministry of Economy Official Legal
 *     Translation 2022". That is the single worst line in any export so far: it
 *     tells a practitioner the invented text above it has been certified by two
 *     named ministries. Everything else on the page is a fabrication; this one
 *     is a forged provenance for it.
 *
 *   · INVENTED CASE LAW WITH HOLDINGS. "UAE Fed. Sup. Ct. / Appeal 412/2023"
 *     and "Dubai Cassation / Case 89/2022", each with a quoted ratio in
 *     quotation marks, a bench, a decision date, and a "binding" label. The two
 *     locales again disagree: the English gives Appeal 412/2023 a date of 14
 *     November 2023 and the Arabic gives it 14 May 2023.
 *
 *   · A CROSS-JURISDICTIONAL EQUIVALENCE TABLE. UAE Article 71(2) against
 *     "DIFC Companies Law No. 5/2018 Section 14 & Reg. 4.2" and "ADGM Companies
 *     Regulations 2020 Section 544", with notice periods and a verdict column
 *     reading "No conflict detected". That is comparative legal advice, on
 *     three real instruments, generated by nothing.
 *
 *   · "Match Confidence: 99.4%" and "متوافق 100%" — the forbidden shape, now
 *     attached to a compliance opinion about a live matter.
 *
 *   · CURRENCY AND PROVENANCE CLAIMS. "In Force (Enacted 20 Sep 2021, Effective
 *     2 Jan 2022)", "Amended by Fed. Decree-Law No. 51/2023", "Official Gazette
 *     Issue No. 712, p. 11", per-article page numbers, and "363 Articles
 *     codified" over a corpus of four. Whether an instrument is still in force
 *     is the one fact a practitioner most needs right.
 *
 *   · "Insert Section into Active Canvas [MAT-2204]" and "Apply to Draft" —
 *     writing fabricated statutory text into a document that has no body, on a
 *     matter that is not on this firm's register. Plus "AI Legal Synthesis",
 *     a "Precedents (14)" tab, an "Amendments" tab, a Gazette PDF download, and
 *     "Hash: sha256-49a0f3d9b0c2a718e223".
 *
 * ===========================================================================
 * WHAT IS REAL HERE
 * ===========================================================================
 * The metadata, because it always was: a reference, a kind, an issuing body and
 * an issue date. The section structure, because an instrument has numbered
 * sections and a reader with one paragraph in it proves nothing — see the
 * fixture on why structure is exercised and content is not. Previous and next,
 * because there are four entries in a fixed order. The position counter,
 * counted rather than stated. And copying the reference, which is the one
 * action on the page that fully works.
 *
 * NO TEXT-SIZE CONTROLS, and this is the one refusal that is not about honesty.
 * They would be real — a local CSS change, asserting nothing. But design.md §3
 * owns the type scale, and a per-session override with nowhere to persist is a
 * reading preference, which belongs with the other preferences at Track A.5
 * rather than as a control that forgets itself on every navigation.
 */

export const dynamic = 'force-dynamic';

export default async function LawReaderPage({
  params,
}: {
  params: Promise<{ locale: string; reference: string }>;
}) {
  const { locale, reference } = await params;
  setRequestLocale(locale);

  const record = await mockApi.staff.legalEntry(decodeURIComponent(reference));
  // A reference that names nothing gets the translated 404, not an error page —
  // the same rule the engagement and client detail screens follow.
  if (!record) notFound();

  return <Reader locale={locale as Locale} record={record} />;
}

function Reader({ locale, record }: { locale: Locale; record: LegalEntryRecord }) {
  const t = useTranslations('lawReader');
  const tDb = useTranslations('legalDatabase');
  const { entry, previous, next, position, total } = record;

  return (
    <>
      <StaffTopBar title={entry.title[locale]} subtitle={t('subtitle')} />

      <main className="mx-auto flex w-full max-w-content flex-1 flex-col gap-5 px-6 py-6">
        <Link
          href="/staff/legal-database"
          className="inline-flex w-fit items-center gap-1.5 text-caption text-legal-navy hover:underline"
        >
          {/* A direction, so it mirrors. design.md §12. */}
          <ArrowLeft aria-hidden size={14} className="rtl:rotate-180" />
          {t('back')}
        </Link>

        {/*
          Said BEFORE the text, not under it. Somebody scrolling into a wall of
          Latin should already know why it is there. The second half is the
          claim the export makes and this screen will not: nothing here is
          certified by anybody.
        */}
        <div className="flex items-start gap-3 rounded-card border border-gray-300 bg-gray-100 p-4">
          <Info aria-hidden size={16} className="mt-0.5 shrink-0 text-gray-500" />
          <div className="min-w-0">
            <p className="text-caption font-medium text-gray-700">{t('notice.heading')}</p>
            <p className="mt-1 text-caption text-gray-600">{t('notice.body')}</p>
            <p className="mt-2 text-caption text-gray-600">{t('notice.noProvenance')}</p>
          </div>
        </div>

        <Card padding="lg">
          <div className="flex flex-wrap items-center gap-2">
            {/*
              Sits exactly where a citation would and disqualifies itself on
              sight. Latin in both locales — lib/format.ts's identifier rule.
            */}
            <span dir="ltr" className="font-mono text-reference text-gray-500">
              {entry.reference}
            </span>
            <Badge tone="neutral" icon={null}>
              {tDb(`kinds.${entry.kind}`)}
            </Badge>
            <span className="text-caption text-gray-500">
              <bdi>{entry.jurisdiction[locale]}</bdi>
            </span>
            <span className="text-caption text-gray-500 [unicode-bidi:isolate]">
              {tDb('entry.issued')} {formatCalendarDate(entry.issuedOn, locale, { month: 'long' })}
            </span>
          </div>

          <h2 className="mt-2 font-sans text-title text-gray-900">
            <bdi>{entry.title[locale]}</bdi>
          </h2>

          <div className="mt-3 flex flex-wrap items-center justify-between gap-3 border-t border-gray-200 pt-3">
            {/* Counted off the collection, never stated. */}
            <p className="text-caption text-gray-500">
              {t('position', { position, total })}
            </p>
            <CopyReference reference={entry.reference} />
          </div>
        </Card>

        {/* The text ------------------------------------------------------- */}
        <Card padding="lg">
          <p className="text-caption text-gray-500">{t('sectionsCaption')}</p>

          <ol className="mt-4 flex flex-col gap-5">
            {entry.sections.map((section) => (
              <li key={section.number} className="flex items-start gap-4">
                {/*
                  A section number is structure. There is no heading beside it,
                  because a heading would name what the provision does — see
                  the fixture.
                */}
                <span
                  dir="ltr"
                  className="mt-0.5 shrink-0 rounded-btn bg-gray-100 px-2 py-1 font-mono text-reference text-gray-600"
                >
                  {section.number}
                </span>
                {/*
                  `dir="ltr"` and `text-start` because the text IS Latin — that
                  is correct typography for a Latin paragraph, not the
                  identifier rule. In the Arabic interface it makes the
                  placeholder unmistakable, which is the direction to err in.

                  Dashed and gray, the same treatment Document Canvas gives its
                  empty sections and the result cards give their excerpts, so
                  every screen in the product agrees about what "there is no
                  content here" looks like.
                */}
                <p
                  dir="ltr"
                  className="min-w-0 flex-1 rounded-card border border-dashed border-gray-300 bg-gray-50 p-4 text-start text-body text-gray-500"
                >
                  {section.body}
                </p>
              </li>
            ))}
          </ol>
        </Card>

        {/* Previous / next over four real entries ------------------------- */}
        <nav aria-label={t('navLabel')} className="grid grid-cols-1 gap-3 tablet:grid-cols-2">
          {previous ? (
            <Link
              href={`/staff/legal-database/${previous.reference}`}
              className="flex items-center gap-3 rounded-card border border-gray-200 bg-white p-4 hover:bg-gray-50"
            >
              <ArrowLeft aria-hidden size={16} className="shrink-0 text-gray-500 rtl:rotate-180" />
              <span className="min-w-0">
                <span className="block text-caption text-gray-500">{t('previous')}</span>
                <span className="block truncate text-body text-gray-700">
                  <bdi>{previous.title[locale]}</bdi>
                </span>
              </span>
            </Link>
          ) : (
            // A placeholder keeps "next" at the end of the row rather than
            // sliding it to the start when there is no previous.
            <span />
          )}

          {next ? (
            <Link
              href={`/staff/legal-database/${next.reference}`}
              className="flex items-center justify-end gap-3 rounded-card border border-gray-200 bg-white p-4 text-end hover:bg-gray-50"
            >
              <span className="min-w-0">
                <span className="block text-caption text-gray-500">{t('next')}</span>
                <span className="block truncate text-body text-gray-700">
                  <bdi>{next.title[locale]}</bdi>
                </span>
              </span>
              <ArrowRight aria-hidden size={16} className="shrink-0 text-gray-500 rtl:rotate-180" />
            </Link>
          ) : null}
        </nav>
      </main>
    </>
  );
}
